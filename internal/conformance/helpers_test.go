// Package conformance houses the executable 12-factor conformance suite
// for aim. Each TestFactor* test maps to one factor in the upstream
// 12-factor AI-CLI spec and locks the contract by exercising the
// production wiring (cmd/aim/main.go's command tree, kit's WrapRunE
// middleware, real cache + breaker code paths).
//
// The suite is in-process: every test composes a *cli.Root identical to
// production, calls Cmd.ExecuteContext directly, and asserts on stdout
// + stderr buffers. No subprocess spawn, no network. The cache is
// primed from testdata/api-fixture.json into a per-test XDG temp dir.
//
// See docs/12-factor-conformance.md (auto-regenerated by
// TestGenerateReport) for the canonical PASS/FAIL matrix.
